"""Offline angle robustness diagnosis for rotated object detection results.

The script consumes the pickle produced by ``tools/test.py --out``. It does
not build, modify or run the model. Two complementary analyses are produced:

1. Real prediction angle error after confidence-ordered, class-consistent,
   one-to-one matching with ground truth.
2. Geometric sensitivity when ground-truth boxes are perturbed by fixed
   angles while center, width and height stay unchanged.

Angles of rotated rectangles are periodic by 180 degrees. All reported angle
errors therefore use the smallest equivalent difference in [0, 90] degrees.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import os
import os.path as osp
import pickle
from collections import defaultdict
from typing import Dict, Iterable, List, Sequence, Tuple

import numpy as np
import torch

from ai4rs.structures.bbox import rbbox_overlaps


DEFAULT_CLASSES = ('car', 'truck', 'bus', 'van', 'freight_car')


def parse_args():
    parser = argparse.ArgumentParser(
        description='Diagnose angle errors and angle sensitivity offline')
    parser.add_argument(
        'predictions', help='pickle generated by tools/test.py --out')
    parser.add_argument(
        '--output-dir',
        default='work_dirs/dronevehicle_angle_diagnosis',
        help='directory for diagnosis outputs')
    parser.add_argument(
        '--classes', nargs='+', default=list(DEFAULT_CLASSES),
        help='class names in label-index order')
    parser.add_argument(
        '--score-thr', type=float, default=0.05,
        help='minimum prediction confidence used for matching')
    parser.add_argument(
        '--match-iou-thrs', type=float, nargs='+', default=[0.3, 0.5],
        help='IoU thresholds reported for real prediction matching')
    parser.add_argument(
        '--perturb-degrees', type=float, nargs='+',
        default=[-20, -15, -10, -5, -2, 0, 2, 5, 10, 15, 20],
        help='signed GT angle perturbations in degrees')
    parser.add_argument(
        '--sparse-max-gt', type=int, default=7,
        help='maximum GT count of a sparse image')
    parser.add_argument(
        '--medium-max-gt', type=int, default=16,
        help='maximum GT count of a medium-density image')
    parser.add_argument(
        '--device', choices=('auto', 'cpu', 'cuda'), default='cpu',
        help='device for rotated IoU; CPU is recommended for MMCV 2.0.1')
    parser.add_argument(
        '--max-images', type=int, default=None,
        help='diagnose only the first N images for a smoke test')
    return parser.parse_args()


def as_tensor(value) -> torch.Tensor:
    if hasattr(value, 'tensor'):
        value = value.tensor
    if torch.is_tensor(value):
        return value.detach()
    return torch.as_tensor(value)


def write_csv(path: str, fieldnames: Sequence[str], rows: Iterable[dict]):
    with open(path, 'w', newline='', encoding='utf-8-sig') as file:
        writer = csv.DictWriter(file, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def density_group(num_gt: int, sparse_max: int, medium_max: int) -> str:
    if num_gt <= sparse_max:
        return 'sparse'
    if num_gt <= medium_max:
        return 'medium'
    return 'dense'


def aspect_group(box: torch.Tensor) -> Tuple[str, float]:
    width = max(float(box[2]), 1e-6)
    height = max(float(box[3]), 1e-6)
    ratio = max(width, height) / min(width, height)
    if ratio < 1.5:
        return 'near_square', ratio
    if ratio < 3.0:
        return 'medium', ratio
    return 'elongated', ratio


def long_axis_angle(box: torch.Tensor) -> float:
    """Return the orientation of the rectangle's long axis.

    Rotated boxes have an additional equivalence:
    ``(w, h, theta) == (h, w, theta + pi/2)``. Comparing raw theta values
    therefore produces false errors close to 90 degrees when two equivalent
    boxes use different width/height parameterizations.
    """
    angle = float(box[4].item())
    if float(box[2].item()) < float(box[3].item()):
        angle += math.pi / 2
    return angle


def periodic_angle_error_deg(pred_box: torch.Tensor,
                             gt_box: torch.Tensor) -> float:
    """Smallest long-axis orientation difference in [0, 90] degrees."""
    difference = abs(long_axis_angle(pred_box) -
                     long_axis_angle(gt_box)) % math.pi
    difference = min(difference, math.pi - difference)
    return math.degrees(difference)


def summarize_values(values: Sequence[float]) -> Dict[str, float]:
    if not values:
        return {
            'count': 0,
            'mean_angle_error_deg': '',
            'median_angle_error_deg': '',
            'p90_angle_error_deg': '',
            'angle_error_le_5_rate': '',
            'angle_error_le_10_rate': '',
            'angle_error_le_15_rate': '',
        }
    array = np.asarray(values, dtype=np.float64)
    return {
        'count': int(array.size),
        'mean_angle_error_deg': float(array.mean()),
        'median_angle_error_deg': float(np.median(array)),
        'p90_angle_error_deg': float(np.percentile(array, 90)),
        'angle_error_le_5_rate': float((array <= 5).mean()),
        'angle_error_le_10_rate': float((array <= 10).mean()),
        'angle_error_le_15_rate': float((array <= 15).mean()),
    }


def greedy_match(pred_boxes: torch.Tensor, pred_scores: torch.Tensor,
                 pred_labels: torch.Tensor, gt_boxes: torch.Tensor,
                 gt_labels: torch.Tensor, iou_thr: float) -> List[Tuple]:
    """Confidence-ordered class-consistent one-to-one matching."""
    if len(pred_boxes) == 0 or len(gt_boxes) == 0:
        return []
    ious = rbbox_overlaps(pred_boxes, gt_boxes)
    order = pred_scores.argsort(descending=True)
    used_gt = torch.zeros(len(gt_boxes), dtype=torch.bool,
                          device=gt_boxes.device)
    matches = []
    for pred_index_tensor in order:
        pred_index = int(pred_index_tensor.item())
        eligible = (gt_labels == pred_labels[pred_index]) & (~used_gt)
        if not bool(eligible.any()):
            continue
        candidate_ious = ious[pred_index].masked_fill(~eligible, -1)
        best_iou, gt_index_tensor = candidate_ious.max(dim=0)
        if float(best_iou) < iou_thr:
            continue
        gt_index = int(gt_index_tensor.item())
        used_gt[gt_index] = True
        matches.append((pred_index, gt_index, float(best_iou),
                        float(pred_scores[pred_index])))
    return matches


def aggregate_match_details(details: List[dict], class_names: Sequence[str],
                            thresholds: Sequence[float]):
    rows = []
    group_specs = [
        ('overall', ['all']),
        ('class', list(class_names)),
        ('density', ['sparse', 'medium', 'dense']),
        ('aspect_ratio', ['near_square', 'medium', 'elongated']),
    ]
    for threshold in thresholds:
        threshold_details = [
            row for row in details if row['match_iou_threshold'] == threshold
        ]
        for group_type, group_names in group_specs:
            for group_name in group_names:
                if group_type == 'overall':
                    selected = threshold_details
                elif group_type == 'class':
                    selected = [r for r in threshold_details
                                if r['class'] == group_name]
                elif group_type == 'density':
                    selected = [r for r in threshold_details
                                if r['density_group'] == group_name]
                else:
                    selected = [r for r in threshold_details
                                if r['aspect_ratio_group'] == group_name]
                summary = summarize_values(
                    [r['angle_error_deg'] for r in selected])
                mean_iou = (float(np.mean([r['rotated_iou'] for r in selected]))
                            if selected else '')
                mean_score = (float(np.mean([r['score'] for r in selected]))
                              if selected else '')
                rows.append({
                    'match_iou_threshold': threshold,
                    'group_type': group_type,
                    'group': group_name,
                    **summary,
                    'mean_rotated_iou': mean_iou,
                    'mean_score': mean_score,
                })
    return rows


def update_perturbation_stats(stats, degree: float, group_type: str,
                              group_name: str, value: float):
    item = stats[(float(degree), group_type, group_name)]
    item['count'] += 1
    item['sum_iou'] += value
    item['ge_05'] += int(value >= 0.5)
    item['ge_075'] += int(value >= 0.75)


def finalize_perturbation_stats(stats):
    output = []
    for (degree, group_type, group_name), item in sorted(
            stats.items(), key=lambda entry: (entry[0][0], entry[0][1],
                                               entry[0][2])):
        count = item['count']
        output.append({
            'perturbation_deg': degree,
            'group_type': group_type,
            'group': group_name,
            'count': count,
            'mean_iou': item['sum_iou'] / count if count else '',
            'iou_ge_0.5_rate': item['ge_05'] / count if count else '',
            'iou_ge_0.75_rate': item['ge_075'] / count if count else '',
        })
    return output


def main():
    args = parse_args()
    if not 0 <= args.score_thr <= 1:
        raise ValueError('--score-thr must be between 0 and 1.')
    if any(not 0 < value <= 1 for value in args.match_iou_thrs):
        raise ValueError('--match-iou-thrs must be in (0, 1].')
    if args.sparse_max_gt >= args.medium_max_gt:
        raise ValueError('sparse threshold must be smaller than medium.')

    if args.device == 'auto':
        # MMCV 2.0.1's CUDA aligned rotated-IoU kernel can return incorrect
        # values for a batch of identical boxes on this Windows environment.
        # The CPU kernel is deterministic and returns IoU=1 as required.
        device = torch.device('cpu')
    else:
        device = torch.device(args.device)

    with open(args.predictions, 'rb') as file:
        predictions = pickle.load(file)
    if args.max_images is not None:
        predictions = predictions[:args.max_images]

    os.makedirs(args.output_dir, exist_ok=True)
    match_details = []
    perturbation_stats = defaultdict(
        lambda: dict(count=0, sum_iou=0.0, ge_05=0, ge_075=0))
    image_gt_counts = []
    total_predictions_after_threshold = 0

    for image_index, result in enumerate(predictions):
        pred_instances = result['pred_instances']
        gt_instances = result['gt_instances']

        pred_boxes = as_tensor(pred_instances['bboxes']).float()
        pred_scores = as_tensor(pred_instances['scores']).float()
        pred_labels = as_tensor(pred_instances['labels']).long()
        gt_boxes = as_tensor(gt_instances['bboxes']).float()
        gt_labels = as_tensor(gt_instances['labels']).long()

        score_mask = pred_scores >= args.score_thr
        pred_boxes = pred_boxes[score_mask].to(device)
        pred_scores = pred_scores[score_mask].to(device)
        pred_labels = pred_labels[score_mask].to(device)
        gt_boxes = gt_boxes.to(device)
        gt_labels = gt_labels.to(device)

        num_gt = len(gt_boxes)
        image_gt_counts.append(num_gt)
        total_predictions_after_threshold += len(pred_boxes)
        image_density = density_group(
            num_gt, args.sparse_max_gt, args.medium_max_gt)
        img_id = str(result.get('img_id', image_index))
        img_path = result.get('img_path', '')

        # Actual prediction angle errors at two IoU thresholds.
        for iou_threshold in sorted(set(args.match_iou_thrs)):
            matches = greedy_match(
                pred_boxes, pred_scores, pred_labels,
                gt_boxes, gt_labels, iou_threshold)
            for pred_index, gt_index, iou, score in matches:
                class_id = int(gt_labels[gt_index].item())
                class_name = (args.classes[class_id]
                              if class_id < len(args.classes)
                              else str(class_id))
                ratio_name, ratio = aspect_group(gt_boxes[gt_index])
                pred_angle = float(pred_boxes[pred_index, 4].item())
                gt_angle = float(gt_boxes[gt_index, 4].item())
                match_details.append({
                    'img_id': img_id,
                    'img_path': img_path,
                    'num_gt_in_image': num_gt,
                    'density_group': image_density,
                    'match_iou_threshold': iou_threshold,
                    'class_id': class_id,
                    'class': class_name,
                    'score': score,
                    'rotated_iou': iou,
                    'aspect_ratio': ratio,
                    'aspect_ratio_group': ratio_name,
                    'pred_angle_deg': math.degrees(pred_angle),
                    'gt_angle_deg': math.degrees(gt_angle),
                    'pred_long_axis_angle_deg': math.degrees(
                        long_axis_angle(pred_boxes[pred_index])),
                    'gt_long_axis_angle_deg': math.degrees(
                        long_axis_angle(gt_boxes[gt_index])),
                    'angle_error_deg': periodic_angle_error_deg(
                        pred_boxes[pred_index], gt_boxes[gt_index]),
                })

        # Pure geometry sensitivity of every GT to signed angle perturbation.
        if num_gt > 0:
            for degree in args.perturb_degrees:
                perturbed = gt_boxes.clone()
                perturbed[:, 4] += math.radians(degree)
                aligned_iou = rbbox_overlaps(
                    gt_boxes, perturbed, is_aligned=True)
                for gt_index in range(num_gt):
                    class_id = int(gt_labels[gt_index].item())
                    class_name = (args.classes[class_id]
                                  if class_id < len(args.classes)
                                  else str(class_id))
                    ratio_name, ratio = aspect_group(gt_boxes[gt_index])
                    value = float(aligned_iou[gt_index].item())
                    update_perturbation_stats(
                        perturbation_stats, degree, 'overall', 'all', value)
                    update_perturbation_stats(
                        perturbation_stats, degree, 'class', class_name, value)
                    update_perturbation_stats(
                        perturbation_stats, degree, 'density', image_density,
                        value)
                    update_perturbation_stats(
                        perturbation_stats, degree, 'aspect_ratio', ratio_name,
                        value)

        if image_index % 200 == 0:
            print(f'[angle diagnosis] processed {image_index + 1}/'
                  f'{len(predictions)} images')

    aggregate_rows = aggregate_match_details(
        match_details, args.classes, sorted(set(args.match_iou_thrs)))
    perturbation_rows = finalize_perturbation_stats(perturbation_stats)

    detail_fields = [
        'img_id', 'img_path', 'num_gt_in_image', 'density_group',
        'match_iou_threshold', 'class_id', 'class', 'score', 'rotated_iou',
        'aspect_ratio', 'aspect_ratio_group', 'pred_angle_deg',
        'gt_angle_deg', 'pred_long_axis_angle_deg',
        'gt_long_axis_angle_deg', 'angle_error_deg'
    ]
    aggregate_fields = [
        'match_iou_threshold', 'group_type', 'group', 'count',
        'mean_angle_error_deg', 'median_angle_error_deg',
        'p90_angle_error_deg', 'angle_error_le_5_rate',
        'angle_error_le_10_rate', 'angle_error_le_15_rate',
        'mean_rotated_iou', 'mean_score'
    ]
    perturbation_fields = [
        'perturbation_deg', 'group_type', 'group', 'count', 'mean_iou',
        'iou_ge_0.5_rate', 'iou_ge_0.75_rate'
    ]

    write_csv(osp.join(args.output_dir, 'matched_angle_details.csv'),
              detail_fields, match_details)
    write_csv(osp.join(args.output_dir, 'angle_error_summary.csv'),
              aggregate_fields, aggregate_rows)
    write_csv(osp.join(args.output_dir, 'angle_perturbation_sensitivity.csv'),
              perturbation_fields, perturbation_rows)

    summary = {
        'predictions_file': osp.abspath(args.predictions),
        'images': len(predictions),
        'total_gt': int(sum(image_gt_counts)),
        'predictions_after_score_threshold':
            int(total_predictions_after_threshold),
        'score_threshold': args.score_thr,
        'match_iou_thresholds': sorted(set(args.match_iou_thrs)),
        'perturbation_degrees': sorted(set(args.perturb_degrees)),
        'density_thresholds': {
            'sparse_max_gt': args.sparse_max_gt,
            'medium_max_gt': args.medium_max_gt,
        },
        'aspect_ratio_groups': {
            'near_square': 'ratio < 1.5',
            'medium': '1.5 <= ratio < 3.0',
            'elongated': 'ratio >= 3.0',
        },
        'matching': (
            'confidence-ordered, class-consistent, one-to-one greedy matching'),
        'angle_periodicity': '180 degrees with 90-degree width/height equivalence',
        'device': str(device),
        'notes': [
            'Actual angle error and pure geometric perturbation sensitivity '
            'must be interpreted together.',
            'The perturbation experiment alone does not prove a model defect.',
            'Rotation-equivariance testing requires rotated-image inference '
            'and is intentionally not included in this offline first stage.',
        ],
    }
    with open(osp.join(args.output_dir, 'angle_diagnosis_summary.json'), 'w',
              encoding='utf-8') as file:
        json.dump(summary, file, ensure_ascii=False, indent=2)

    print(json.dumps(summary, ensure_ascii=False, indent=2))
    print(f'Angle diagnosis saved to: {osp.abspath(args.output_dir)}')


if __name__ == '__main__':
    main()
